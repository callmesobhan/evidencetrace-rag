"""Write data/m1/ATTRIBUTION.md: who wrote every paper whose sentences the data files quote, and under what licence.

    python scripts/make_attribution.py          # needs the papers: run `make fetch-pinned` first

Authors, journal, year, DOI, full title and the copyright statement come from each paper's own JATS metadata, not from
the manifest, so the credit line is the authors' own. CC BY 4.0 requires naming the creator(s), linking the licence and
indicating changes; the preamble does the last, and every row links the original article.
"""

from __future__ import annotations

import json
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
M1 = ROOT / "data" / "m1"
MAX_AUTHORS = 6

HEAD = """# Attribution

The annotation, gold, prediction and report files in `data/m1/` quote sentences (about 200,000 characters in total,
mostly in `annotation/*_candidates.jsonl` and `*_nearmiss.jsonl`) from the {n} open-access articles below. Each is
published in PubMed Central under **CC BY 4.0** (https://creativecommons.org/licenses/by/4.0/). The licence of every article
was re-read from its own XML on 2026-10-27 (`data/raw/NOTICE.md`).

**Changes made to the quoted text:** passages are excerpted (single sentences or short spans), Unicode is normalised
(NFKC; hyphen variants mapped to "-"; line breaks and a few control characters folded; Lancet-style middle-dot decimals
`0·78` read as `0.78`), and tables, figures and formulae are dropped before sentences are cut. Nothing is paraphrased.
The full text of {committed} of the articles is committed under `data/raw/pmc/` and `data/raw/fresh/`, under the terms in
`data/raw/NOTICE.md`. The {excluded} marked **not committed** are not, because their licence terms are not clear; follow the link in each row to the original.

The software in this repository is MIT-licensed (see `LICENSE`). **That licence does not apply to these quotations or to the
full text under `data/raw/`**, which remain under their authors' CC BY terms.

Generated by `scripts/make_attribution.py` from the JATS metadata of `corpus_manifest.jsonl` and `fresh_manifest.jsonl`.

| PMCID | role | citation | licence / copyright |
|---|---|---|---|
"""


def _text(el: ET.Element | None) -> str:
    return " ".join("".join(el.itertext()).split()) if el is not None else ""


def _authors(root: ET.Element) -> str:
    names = []
    for c in root.iter("contrib"):
        if c.get("contrib-type") != "author":
            continue
        nm = c.find("name")
        if nm is not None:
            sur, given = _text(nm.find("surname")), _text(nm.find("given-names"))
            names.append(f"{sur} {''.join(w[0] for w in given.replace('-', ' ').split())}".strip())
        elif c.find("collab") is not None:
            names.append(_text(c.find("collab")))
    more = ", et al." if len(names) > MAX_AUTHORS else ""
    return (", ".join(names[:MAX_AUTHORS]) + more) or "(authors not given in the metadata)"


def _row(pmcid: str, role: str, raw: Path, licence: str, note: str = "") -> str:
    root = ET.parse(raw / f"{pmcid}.xml").getroot()
    meta = root.find(".//article-meta")
    doi = next((_text(a) for a in root.iter("article-id") if a.get("pub-id-type") == "doi"), "")
    year = _text(meta.find("pub-date/year")) if meta is not None and meta.find("pub-date/year") is not None else next((_text(y) for y in root.iter("year")), "")
    journal = _text(root.find(".//journal-title"))
    title = _text(meta.find(".//article-title")) if meta is not None else ""
    lic = next((li.get("{http://www.w3.org/1999/xlink}href", "") for li in root.iter("license") if li.get("{http://www.w3.org/1999/xlink}href")), "")
    lic = lic or f"https://{licence}"  # the licence URL recorded in the manifest when the paper was downloaded
    stmt = _text(root.find(".//copyright-statement"))[:160]
    cite = f"{_authors(root)} ({year}). {title}. *{journal}*." + (f" https://doi.org/{doi}" if doi else "")
    link = f"[{pmcid}](https://pmc.ncbi.nlm.nih.gov/articles/{pmcid}/)"
    return f"| {link} | {role} | {cite.replace('|', '/')} | {(stmt + ' ' if stmt else '')}{lic}{note}".replace("|  ", "| ") + " |"


def main() -> int:
    sources = [(M1 / "corpus_manifest.jsonl", ROOT / "data" / "raw" / "pmc"), (M1 / "fresh_manifest.jsonl", ROOT / "data" / "raw" / "fresh")]
    excluded = {e["pmcid"] for e in json.loads((ROOT / "data" / "raw" / "excluded.json").read_text(encoding="utf-8"))["excluded"]}
    rows = []
    for manifest, raw in sources:
        for ln in manifest.read_text(encoding="utf-8").splitlines():
            if ln.strip():
                r = json.loads(ln)
                if not (raw / f"{r['pmcid']}.xml").exists():
                    sys.exit(f"missing {raw / (r['pmcid'] + '.xml')}: run `make fetch-pinned` first")
                rows.append((r["split"], r["pmcid"], raw, r["license"]))
    rows.sort()
    note = " **Full text not committed** (`data/raw/NOTICE.md`)."
    words = {1: "one", 2: "two", 3: "three"}
    head = HEAD.format(n=len(rows), committed=len(rows) - len(excluded), excluded=words.get(len(excluded), str(len(excluded))))
    body = "\n".join(_row(p, s, raw, lic, note if p in excluded else "") for s, p, raw, lic in rows)
    (M1 / "ATTRIBUTION.md").write_text(head + body + "\n", encoding="utf-8")
    print(f"{len(rows)} articles ({len(rows) - len(excluded)} committed) -> data/m1/ATTRIBUTION.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
